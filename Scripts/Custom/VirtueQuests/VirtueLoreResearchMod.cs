    public class VirtueLoreBookGump : Server.Gumps.Gump
    {
        public VirtueLoreBookGump(string title, string text) : base(150, 100)
        {
            AddPage(0);
            AddBackground(0, 0, 420, 320, 0x1E46);
            AddAlphaRegion(15, 15, 390, 290);
            AddLabel(50, 30, 2418, $"Результат анализа: {title}");
            AddImageTiled(35, 55, 350, 2, 0x2424);
            AddHtml(40, 75, 340, 180, $"{text}", false, true);
            AddButton(170, 265, 0x15E1, 0x15E5, 0, Server.Gumps.GumpButtonType.Reply, 0);
            AddLabel(200, 267, 0x35, "Закрыть");
        }
